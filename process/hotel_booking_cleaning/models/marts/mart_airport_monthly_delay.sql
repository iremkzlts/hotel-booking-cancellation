
SELECT
    APT_ICAO AS AIRPORT,

    CAST(
        DATE_TRUNC('month', FLT_DATE) AS DATE
    ) AS AY_BASLANGICI,

    COUNT(*) AS TOPLAM_UCUS,

    COUNT(DLY_APT_ARR_1) AS GECIKME_VERISI_BULUNAN_UCUS,

    ROUND(AVG(DLY_APT_ARR_1), 2) AS ORTALAMA_GECIKME,

    ROUND(MAX(DLY_APT_ARR_1), 2) AS MAKSIMUM_GECIKME,

    ROUND(MIN(DLY_APT_ARR_1), 2) AS MINIMUM_GECIKME

FROM {{ ref('stg_eurocontrol') }}

GROUP BY
    APT_ICAO,
    DATE_TRUNC('month', FLT_DATE)

ORDER BY
    AY_BASLANGICI,
    AIRPORT

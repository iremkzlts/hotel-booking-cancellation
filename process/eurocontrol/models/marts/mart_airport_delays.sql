SELECT
    APT_ICAO AS AIRPORT,
    COUNT(*) AS TOPLAM_KAYIT,
    COUNT(DLY_APT_ARR_1) AS GECIKME_VERISI_BULUNAN_KAYIT,
    ROUND(AVG(DLY_APT_ARR_1), 2) AS ORTALAMA_GECIKME,
    ROUND(MAX(DLY_APT_ARR_1), 2) AS MAKSIMUM_GECIKME,
    ROUND(MIN(DLY_APT_ARR_1), 2) AS MINIMUM_GECIKME
FROM {{ ref('stg_eurocontrol') }}
GROUP BY APT_ICAO
ORDER BY ORTALAMA_GECIKME DESC